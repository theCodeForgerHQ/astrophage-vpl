type FloatArray = NDArray[np.float64]

# ─── the verification-fixture level system ─────────────────────────────────────────
#
# "Argon-shaped, not argon" — see the module docstring. Values follow
# `packages/vpl-instruments/tests/oes_system.py`'s own convention so that a reader who
# already knows that fixture recognises this one; they are not independently sourced and
# must never be read as atomic data (doc 00 C1).

_GROUND: Final[str] = "g"
_METASTABLE: Final[str] = "m"
_RADIATING: Final[str] = "p"

_METASTABLE_ENERGY_EV: Final[float] = 11.5
_RADIATING_ENERGY_EV: Final[float] = 13.1
_METASTABLE_DEGENERACY: Final[int] = 5
_RADIATING_DEGENERACY: Final[int] = 7

_LINE_WAVELENGTH_NM: Final[float] = 811.53
_LINE_A_UL_PER_S: Final[float] = 3.31e7

_ENERGY_GRID_MAX_EV: Final[float] = 60.0
_ENERGY_GRID_CELLS: Final[int] = 600

#: doc 04 §2.2's `nu_wall` for the metastable: "diffusion to wall + surface quenching
#: probability", a chamber property rather than an atomic one. `cr.py`'s own module
#: docstring records the RP-1 order of magnitude — "the ~1e4 /s wall term" — which is what
#: is used here; a real value belongs to a doc 02 §3 chamber-geometry registry entry that
#: does not yet exist (the same gap `OES.chamber_diameter`'s own docstring records).
_METASTABLE_WALL_LOSS_PER_S: Final[float] = 1.0e4

#: Born-like threshold cross sections for the three electron-impact channels, in m^2 at
#: their peak. Shaped, not measured — see `oes_system.py`'s `threshold_cross_section`.
_XSEC_GROUND_TO_METASTABLE_PEAK_M2: Final[float] = 3.0e-21
_XSEC_GROUND_TO_RADIATING_PEAK_M2: Final[float] = 1.0e-21
_XSEC_METASTABLE_TO_RADIATING_PEAK_M2: Final[float] = 5.0e-20
_RADIATING_THRESHOLD_FROM_METASTABLE_EV: Final[float] = _RADIATING_ENERGY_EV - _METASTABLE_ENERGY_EV


def _threshold_cross_section(
    energy_ev: FloatArray, *, threshold_ev: float, peak_m2: float
) -> FloatArray:
    """``sigma = peak * (1 - threshold/eps)`` above threshold, zero below — a Born-like shape.

    Copied from `oes_system.py`'s helper of the same name rather than imported: that module
    lives under `packages/vpl-instruments/tests`, which is not an importable package (its
    own docstring gives the reason — more than one person develops that suite at once, and
    a shared helper is the file they collide on). Duplicating four lines is cheaper than
    inventing a cross-test-suite import path for a fixture that is not meant to be load-bearing
    anywhere else.
    """
    above = energy_ev > threshold_ev
    return np.asarray(
        np.where(above, peak_m2 * (1.0 - threshold_ev / np.where(above, energy_ev, 1.0)), 0.0)
    )


def _reference_level_system(grid: EnergyGrid) -> LevelSystem:
    """Ground, metastable and radiating levels, one emission line — see the module docstring."""

    def channel(
        *, lower: str, upper: str, threshold_ev: float, peak_m2: float
    ) -> ElectronImpactChannel:
        return ElectronImpactChannel.from_sampler(
            grid,
            lower=lower,
            upper=upper,
            threshold_ev=threshold_ev,
            sampler=lambda e: _threshold_cross_section(
                e, threshold_ev=threshold_ev, peak_m2=peak_m2
            ),
        )

    return LevelSystem(
        levels=(
            Level(label=_GROUND, energy_ev=0.0, degeneracy=1),
            Level(
                label=_METASTABLE,
                energy_ev=_METASTABLE_ENERGY_EV,
                degeneracy=_METASTABLE_DEGENERACY,
                is_metastable=True,
            ),
            Level(
                label=_RADIATING, energy_ev=_RADIATING_ENERGY_EV, degeneracy=_RADIATING_DEGENERACY
            ),
        ),
        electron_impact=(
            channel(
                lower=_GROUND,
                upper=_METASTABLE,
                threshold_ev=_METASTABLE_ENERGY_EV,
                peak_m2=_XSEC_GROUND_TO_METASTABLE_PEAK_M2,
            ),
            channel(
                lower=_GROUND,
                upper=_RADIATING,
                threshold_ev=_RADIATING_ENERGY_EV,
                peak_m2=_XSEC_GROUND_TO_RADIATING_PEAK_M2,
            ),
            channel(
                lower=_METASTABLE,
                upper=_RADIATING,
                threshold_ev=_RADIATING_THRESHOLD_FROM_METASTABLE_EV,
                peak_m2=_XSEC_METASTABLE_TO_RADIATING_PEAK_M2,
            ),
        ),
        radiative=(
            RadiativeChannel(
                upper=_RADIATING,
                lower=_METASTABLE,
                a_ul_per_s=_LINE_A_UL_PER_S,
                wavelength_nm=_LINE_WAVELENGTH_NM,
            ),
        ),
    )


#: OES accumulations. Chosen (doc 04 §9's shared `_sample` code path) so that the brightest
#: pixels of the 811.53 nm line cross `OES.poisson_gaussian_threshold` under noise (doc 05
#: §3.1's switch is genuinely exercised at T1) while the wings stay in the Poisson regime —
#: verified empirically for this fixture rather than derived, because the photon budget of a
#: three-level synthetic system has no closed form to derive it from.
_ACCUMULATIONS: Final[int] = 2000

#: T0's continuum-residual objective (see `_t0_log_likelihood`) needs a positive scale to
#: turn a sum of squared residuals into a log-density; because that scale multiplies every
#: term identically, it does not move the location of the optimum (the objective is a
#: constant rescaling of the sum of squares), but it does condition the finite-difference
#: gradient `vpl.inverse.map` computes. Too tight (1e-6 relative, checked empirically) makes
#: the gradient numerically noisy enough to abort the line search; this value converges
#: cleanly and is *not* a claim about measurement noise — T0 has none by definition.
_T0_SIGMA_RELATIVE_SCALE: Final[float] = 1.0e-3

#: doc 05 §7.2's "recovery to numerical tolerance", concretely: the relative error on
#: `Gamma_E` a T0 run must not exceed. L-BFGS-B's `ftol`-driven stopping criterion (doc 05
#: §5's `_FUNCTION_TOLERANCE`) means the achieved error varies a little with the sealed
#: seed — observed between 1e-11 and 4e-5 across several seeds in this configuration — so
#: this is set with a comfortable margin above the loosest of those, not tuned to whatever
#: one run happened to produce. It is still four to five orders of magnitude tighter than a
#: typical T1 (noisy) relative error, which is what makes it "numerical" rather than
#: "statistical" tolerance.
T0_RELATIVE_TOLERANCE: Final[float] = 1.0e-3

#: Spatial grid: two sheath thicknesses (doc 01 R-SPAT-3 asks for >= 10 for the full
#: physics domain; two is enough of the profile for the OES local-CR-solve dependence on
#: `n_e(z)` this harness relies on) at eleven points. Both were tuned empirically against
#: T0's tolerance — see the module docstring's account of the grid-aliasing bug this
#: configuration was chosen to avoid reintroducing.
_DOMAIN_SHEATHS: Final[float] = 2.0
_N_SPATIAL_POINTS: Final[int] = 11

#: Multiplicative offsets applied to RP-1's `n_0` and `T_e` to build the sealed truth. Kept
#: away from 1.0 so that the default MAP start (the prior median, which coincides with RP-1
#: for both `n_0` and `T_e` — see `_reference_theta`) is never the answer by construction;
#: a harness that "recovered" its own starting point would prove nothing about the search.
_TRUE_N0_FACTOR_RANGE: Final[tuple[float, float]] = (1.15, 1.45)
_TRUE_TE_FACTOR_RANGE: Final[tuple[float, float]] = (1.10, 1.30)

_GAS_SPECIES_NAME: Final[str] = "Ar+"
_GAS_MASS_ENTRY: Final[str] = "species.Ar.mass"
_SINGLY_IONISED: Final[int] = 1

_LOG_TRANSFORM: Final = LogTransform()


# ─── theta <-> PlasmaParams ─────────────────────────────────────────────────────────


def _argon_ion(registry: ParameterRegistry) -> Species:
    """The one species this harness runs — doc 01 §2.1's Ar+, from the registry."""
    return Species(
        name=_GAS_SPECIES_NAME,
        mass=registry[_GAS_MASS_ENTRY].quantity,
        charge_number=_SINGLY_IONISED,
    )


def _to_plasma_params(
    theta: ControlParameters, *, species: Species, registry: ParameterRegistry
) -> PlasmaParams:
    """The full doc 05 §2.1 vector plus the gas temperature, as a steady, DC state.

    `T_g` is not part of `theta_c`; it is a fixed instrument/gas setting read from the
    registry for both the truth and every trial, exactly as `resolve_plasma` (doc 08 §6)
    does for a manifest that does not state it.
    """
    return PlasmaParams(
        species=species,
        n_0=Q_(theta.n_0, "m**-3"),
        T_e=Q_(theta.T_e, "eV"),
        T_i=Q_(theta.T_i, "eV"),
        T_g=registry.quantity("RP1.T_g"),
        pressure=Q_(theta.p, "mTorr"),
        bias=Q_(theta.V_w, "V"),
        gamma_se=theta.gamma_se,
        kappa=theta.kappa,
        rf_frequency=None,
        rf_phase=theta.phi_RF,
    )


# ─── the OES instrument ─────────────────────────────────────────────────────────────


def _reference_oes_instrument(*, seed: int, registry: ParameterRegistry) -> OesInstrument:
    grid = EnergyGrid.linear(max_ev=_ENERGY_GRID_MAX_EV, n_cells=_ENERGY_GRID_CELLS)
    model = CollisionalRadiativeModel(
        system=_reference_level_system(grid),
        grid=grid,
        wall_loss_per_s={_METASTABLE: _METASTABLE_WALL_LOSS_PER_S},
    )
    instrument = OesInstrument(
        model=model,
        spectrograph=Spectrograph.from_registry(registry),
        # The verification fallback, not the default — see the module docstring on why
        # `kappa` is fixed rather than recovered: this is the reason it never reaches OES.
        eedf=MaxwellianEedf(grid=grid),
        centre_wavelength_nm=_LINE_WAVELENGTH_NM,
        root_seed=seed,
        accumulations=_ACCUMULATIONS,
    )
    instrument.calibrate(_calibration_set(registry))
    return instrument


def _calibration_set(registry: ParameterRegistry) -> CalibrationSet:
    """One standard, for the one radiometric coefficient `OesInstrument.calibrate` derives.

    doc 04 §7.3: the *estimated* response, drawn once from the standard's own registered
    uncertainty — never the true one, except deliberately at T0 (see `_run`).
    """
    uncertainty = float(registry.value_in("OES-C1.radiometric_uncertainty", "dimensionless"))
    return CalibrationSet.of(
        CalibrationReference(
            name="NIST FEL tungsten-halogen lamp",
            quantity="absolute_radiometric",
            value=Q_(1.0, "dimensionless"),
            relative_uncertainty=uncertainty,
            traceable_to="NIST FEL scale",
        )
    )


def _acquisition_window(registry: ParameterRegistry) -> AcquisitionWindow:
    """One ICCD gate at `t = 0` — doc 02 §6.2 OES-D2, the minimum gate width."""
    return AcquisitionWindow.absolute(
        start=Q_(0.0, "s"), duration=registry.quantity("OES-D2.gate_width")
    )


# ─── the reduced (n_0, T_e) prior ───────────────────────────────────────────────────


@dataclass(frozen=True, slots=True)
class _ReducedMedian:
    """What `maximum_a_posteriori`'s default start needs — mirrors `ControlPrior.median`."""

    n_0: float
    T_e: float

    def to_unconstrained(self) -> FloatArray:
        return np.array(
            [_LOG_TRANSFORM.to_unconstrained(self.n_0), _LOG_TRANSFORM.to_unconstrained(self.T_e)],
            dtype=np.float64,
        )


@dataclass(frozen=True, slots=True)
class _ReducedPrior:
    """`p_u(u)` for the two-parameter `(n_0, T_e)` subvector this harness recovers.

    The marginals are *not* reimplemented here: they are pulled from
    `default_control_prior()`, doc 05 §2.1's own log-uniform `n_0` and log-normal `T_e`
    priors, so this harness's prior cannot silently drift from the one doc 05 specifies.
    Only the change-of-variables plumbing — restricted to two coordinates instead of eight
    — is written out, using the same `LogTransform` every `n_0`/`T_e` conversion in
    `vpl.inverse.parameters` uses.
    """

    n_0: Prior
    T_e: Prior

    def log_prob_unconstrained(self, u: FloatArray) -> float:
        vector = np.asarray(u, dtype=np.float64).ravel()
        if vector.size != 2:
            raise ValueError(f"expected a 2-vector (log n_0, log T_e), got size {vector.size}")

        n0_u, te_u = float(vector[0]), float(vector[1])
        log_n0 = self.n_0.log_prob(_LOG_TRANSFORM.to_constrained(n0_u))
        if not math.isfinite(log_n0):
            return -math.inf
        log_te = self.T_e.log_prob(_LOG_TRANSFORM.to_constrained(te_u))
        if not math.isfinite(log_te):
            return -math.inf

        jacobian = _LOG_TRANSFORM.log_abs_det_jacobian(n0_u) + _LOG_TRANSFORM.log_abs_det_jacobian(
            te_u
        )
        return log_n0 + log_te + jacobian

    def median(self) -> _ReducedMedian:
        return _ReducedMedian(n_0=self.n_0.median, T_e=self.T_e.median)


def _reduced_prior() -> _ReducedPrior:
    full = default_control_prior()
    return _ReducedPrior(n_0=full.marginal("n_0"), T_e=full.marginal("T_e"))


def _reference_theta() -> ControlParameters:
    """RP-1, with `n_0` and `T_e` about to be overwritten by the sealed truth or a trial."""
    return ControlParameters.reference()


def _theta_from_unconstrained(u: FloatArray, *, reference: ControlParameters) -> ControlParameters:
    n0 = _LOG_TRANSFORM.to_constrained(float(u[0]))
    te = _LOG_TRANSFORM.to_constrained(float(u[1]))
    return reference.replace(n_0=n0, T_e=te)


# ─── the draw of the sealed truth ───────────────────────────────────────────────────


def _draw_true_theta(*, seed: int, reference: ControlParameters) -> ControlParameters:
    """The ground truth — doc 07 §3 step 1, "draw a ground-truth state x* from the scenario".

    Drawn on `Stream.EXPERIMENT_DESIGN` (doc 10 §5: DOE draws get their own stream, kept
    independent of the photon-statistics and calibration streams the instrument itself
    uses), so the two multiplicative offsets below are reproducible from `seed` alone and
    do not perturb any other stream's sequence.
    """
    rng = generator(seed, Stream.EXPERIMENT_DESIGN)
    n0_factor = rng.uniform(*_TRUE_N0_FACTOR_RANGE)
    te_factor = rng.uniform(*_TRUE_TE_FACTOR_RANGE)
    return reference.replace(n_0=reference.n_0 * n0_factor, T_e=reference.T_e * te_factor)


def _fixed_spatial_grid(
    solver: AnalyticSheathSolver,
    *,
    reference: ControlParameters,
    species: Species,
    registry: ParameterRegistry,
) -> SpatialGrid:
    """One grid, sized off the *reference* thickness — never the sealed truth's.

    See the module docstring's account of the grid-aliasing bug this function exists to
    make structurally impossible to reintroduce: every state this harness solves, truth and
    trial alike, is evaluated on this one array of physical positions.
    """
    reference_params = _to_plasma_params(reference, species=species, registry=registry)
    thickness = solver.thickness(reference_params)
    return SpatialGrid.uniform(length=thickness * _DOMAIN_SHEATHS, n_points=_N_SPATIAL_POINTS)


# ─── the report ──────────────────────────────────────────────────────────────────


@dataclass(frozen=True, slots=True)
class ClosedLoopReport:
    """What one closed-loop run produced — doc 05 §10's "every inversion emits" table.

    Attributes:
        tier: T0, T1 or (never produced by this module — see `run_t2`) T2.
        gamma_e_true_w_per_m2: The sealed truth, readable because `sealed` is committed.
        gamma_e_estimate_w_per_m2: `Gamma_E(theta_hat)`.
        relative_error: `sealed.relative_error` — `|estimate/truth - 1|`.
        n_0_hat_per_m3: Recovered bulk density.
        T_e_hat_ev: Recovered electron temperature.
        map_result: The full `vpl.inverse.map.MapResult`, for a caller that wants the
            gradient, the iteration count or the optimiser's own message.
        sealed: The committed `SealedTruth`, so a caller can run `assert_t0_consistency`
            or `assert_at_least` directly rather than this module reimplementing them.
    """

    tier: Tier
    gamma_e_true_w_per_m2: float
    gamma_e_estimate_w_per_m2: float
    relative_error: float
    n_0_hat_per_m3: float
    T_e_hat_ev: float
    map_result: MapResult
    sealed: SealedTruth


# ─── the loop itself ─────────────────────────────────────────────────────────────


def _t0_log_likelihood(measured: FloatArray, predicted: FloatArray) -> float:
    """The T0 objective: a continuum residual, not the discretised Poisson/Gaussian channel.

    `OesInstrument.likelihood` rounds its radiance-derived counts to the nearest integer
    (`np.rint`) before scoring them — correct for a real, already-quantised measurement, and
    the reason `run_t1` uses it. At T0 the "measurement" is a noise-free continuous
    prediction, and rounding it introduces a quantisation residual that is not the recovery
    error the test is meant to measure; the true generating point can then score slightly
    *worse* than a nearby impostor, which is exactly the kind of self-deception ADR-011
    warns about, just relocated into the likelihood instead of the grid. Comparing the
    continuous radiance directly with `gaussian_log_likelihood` (reused from
    `vpl.inverse.likelihood`, not reimplemented) is the honest T0 objective: it is uniquely
    maximised at the generating `theta`, to floating-point precision, when the forward model
    really is the same one on both sides.
    """
    scale = _T0_SIGMA_RELATIVE_SCALE * max(float(np.max(predicted)), 1.0)
    sigma = np.full_like(predicted, scale)
    return gaussian_log_likelihood(measured, predicted, sigma)


def _run(*, noise: bool, seed: int) -> ClosedLoopReport:
    """doc 07 §3's protocol, steps 1-6, for one tier.

    Args:
        noise: `False` for T0 (doc 05 §7.2: same model, no noise), `True` for T1 (same
            model, with noise). T2 is not reachable through this function — see `run_t2`.
        seed: The single recorded seed everything in the run derives from (doc 00 E3).
    """
    registry = default_registry()
    species = _argon_ion(registry)
    solver = AnalyticSheathSolver()
    instrument = _reference_oes_instrument(seed=seed, registry=registry)
    window = _acquisition_window(registry)

    reference = _reference_theta()
    grid = _fixed_spatial_grid(solver, reference=reference, species=species, registry=registry)

    # ── step 1: draw the ground truth ──────────────────────────────────────────
    true_theta = _draw_true_theta(seed=seed, reference=reference)
    true_params = _to_plasma_params(true_theta, species=species, registry=registry)
    true_state = solver.solve(true_params, grid=grid)

    # ── step 2: run the forward chain -> synthetic measurement ────────────────
    instrument.set_noise_enabled(noise)
    if not noise:
        # doc 04 §7.3 permits the true calibration "for verification"; T0 is exactly that,
        # and CalibrationState.TRUE on the resulting Measurement records that it was used.
        instrument.use_true_calibration()
    measurement = instrument.observe(true_state, window)

    # ── step 3: seal the truth ─────────────────────────────────────────────────
    truth_gamma_e = float(
        magnitude_in(ion_energy_flux(true_params, h_l=solver.h_l, gamma_i=solver.gamma_i), "W/m**2")
    )
    sealed = SealedTruth(value=truth_gamma_e, name="Gamma_E")

    # ── step 4: run the inversion on the (sealed) measurement ─────────────────
    prior = _reduced_prior()

    def log_likelihood(u: FloatArray) -> float:
        theta = _theta_from_unconstrained(u, reference=reference)
        params = _to_plasma_params(theta, species=species, registry=registry)
        state = solver.solve(params, grid=grid)
        predicted = instrument.forward(state, window)
        if noise:
            return instrument.likelihood(measurement, predicted)
        return _t0_log_likelihood(measurement.values, predicted.values)

    result = maximum_a_posteriori(log_likelihood=log_likelihood, prior=prior)
    theta_hat = _theta_from_unconstrained(result.unconstrained, reference=reference)
    params_hat = _to_plasma_params(theta_hat, species=species, registry=registry)
    estimate_gamma_e = float(
        magnitude_in(ion_energy_flux(params_hat, h_l=solver.h_l, gamma_i=solver.gamma_i), "W/m**2")
    )

    # ── step 5: unseal, by committing the estimate at its tier ────────────────
    tier = tier_of_configuration(same_model=True, noise=noise, imperfect_calibration=noise)
    sealed.commit_estimate(estimate_gamma_e, tier=tier)

    # ── step 6: emit the report ────────────────────────────────────────────────
    return ClosedLoopReport(
        tier=sealed.tier,
        gamma_e_true_w_per_m2=float(sealed.value),
        gamma_e_estimate_w_per_m2=float(sealed.estimate),
        relative_error=sealed.relative_error,
        n_0_hat_per_m3=theta_hat.n_0,
        T_e_hat_ev=theta_hat.T_e,
        map_result=result,
        sealed=sealed,
    )


def run_t0(seed: int = 0) -> ClosedLoopReport:
    """T0 — same model, no noise. **Blocking**: doc 05 §7.2 treats a failure here as a bug."""
    return _run(noise=False, seed=seed)


def run_t1(seed: int = 0) -> ClosedLoopReport:
    """T1 — same model, with noise. The optimistic upper bound on achievable accuracy."""
    return _run(noise=True, seed=seed)


def run_t2(seed: int = 0) -> NoReturn:
    """T2 — mismatched models, noise, imperfect calibration. **Not runnable here.**

    doc 05 §7.1 requires the truth-generating model to differ from the inversion's in
    physics level, grid, timestep, collision set, EEDF form *and* calibration, together.
    The only candidate mismatched physics level this project has committed
    (`vpl.physics.fluid.sheath.FluidSheathSolver`, doc 03 §1's L1) depends on `dolfinx`
    (FEniCSx), which is not installed in this environment; the L2 PIC-MCC kernel is out of
    scope for this harness per the task brief (38 minutes per solve on CPU, and another
    agent is still verifying it).

    Raising here, naming the missing piece, is the honest alternative to the tempting
    half-measure: relabelling a same-model T1 run as T2, or mismatching only one of doc 05
    §7.1's required axes (say, `h_l` or `gamma_i` within L0 alone) while calling it T2.
    `vpl.validation.sealed.tier_of_configuration` already refuses the second of those for a
    genuinely mismatched-model run that skips noise or calibration; it has no way to refuse
    a call that mismatches nothing at all and simply claims to, which is why this function
    refuses on this module's behalf instead.
    """
    raise NotImplementedError(
        "T2 needs a truth-generating model that genuinely differs from L0 in physics level, "
        "grid, timestep, collision set, EEDF form and calibration together (doc 05 §7.1). "
        "The only such model committed to this project, vpl.physics.fluid.sheath."
        "FluidSheathSolver (doc 03 §1's L1), depends on dolfinx (FEniCSx), which is not "
        "installed in this environment. Rather than mislabel a same-model T1 run as T2, this "
        "harness says so: T2 cannot be produced here. Install dolfinx and wire "
        "FluidSheathSolver in as the truth solver in _run() to close this gap."
    )
