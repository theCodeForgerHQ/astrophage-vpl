"""The closed-loop recovery harness — doc 05 §7, doc 07 §3, doc 11 §9 item 4 / WBS 3.9.

theta -> L0 forward -> PlasmaState -> OES forward model -> synthetic observation ->
likelihood -> MAP -> theta_hat -> Gamma_E(theta_hat) -> :class:`~vpl.validation.sealed.
SealedTruth` -> tier-labelled report. This module is the one place in the project allowed
to import both :mod:`vpl.physics` and :mod:`vpl.inverse` (doc 08 §3): the inverse layer
stays ignorant of any forward model, and the seam that wires a concrete one to it lives
here rather than being smuggled into either package.

## What a T0 pass here proves, and what it does not

doc 05 §7.2's T0 ("same model, no noise") is deliberately the *only* thing this module
treats as blocking. A T0 pass proves that the forward chain, the OES likelihood, the MAP
engine (:mod:`vpl.inverse.map`) and the sealed-truth barrier (:mod:`vpl.validation.sealed`)
are wired together consistently: given a noise-free synthetic spectrum generated by this
exact L0 + OES chain, the same chain's own inversion can find the parameters that produced
it. **It does not prove the OES model describes a real plasma, and it does not prove the
recovered point is unique** — doc 05 §6's identifiability question is separate, and this
harness answers a narrow piece of it directly (see "Why two parameters, not eight" below).
ADR-011 is the project's own standing reminder that a self-consistent result is not
automatically a correct one; a T0 pass here is a wiring check, not a validation, and the
distinction is the entire point of doc 05 §7's tier discipline.

## A bug this module's own construction found, and now guards against

Early versions of this harness sized the plasma's spatial grid from
:func:`~vpl.physics.analytic.sheath.AnalyticSheathSolver.thickness` evaluated at
**whichever `theta` was currently being tried** (`AnalyticSheathSolver.solve`'s own
`default_grid`, if no explicit grid is supplied, does exactly this). That is wrong for a
closed loop and the error was not obvious: comparing a trial state's radiance to the truth's
radiance *index by index* silently compares different physical positions whenever the trial
`theta` implies a different sheath thickness than the truth did, because the two states then
sit on different physical domains reindexed onto the same array shape. MAP could then reduce
the residual by using the resizing itself to align the profiles, rather than by finding the
right `(n_0, T_e)` — and it did: with a theta-dependent grid, T0 converged to a point 15-20%
from the truth and *reported success*, because the optimiser had found a genuine local
optimum of a subtly wrong objective. **This is the failure test_gamma_e_is_insensitive_to_
the_fixed_control_parameters and test_recovers_gamma_e_to_numerical_tolerance exist to catch
if it is reintroduced**: T0 is blocking specifically so that this class of bug cannot hide
behind a plausible-looking convergence report.

The fix is a spatial grid built **once**, before the search starts, sized from the
*reference* (RP-1) sheath thickness rather than the truth's — every trial `theta` and the
truth are evaluated on the same fixed array of physical positions. This is also the more
honest experimental design: a real spectrograph's field of view is fixed by its optics
before the plasma is characterised, not derived from the unknown state it is about to
measure. Sizing the grid from the *true* thickness instead would be a second, quieter
channel for exactly the inverse-crime doc 05 §7 names — "an initial guess, just to start the
optimiser somewhere sensible" is the shape of self-deception that module's docstring warns
about, and sizing an observation grid from the sealed truth is the same mistake wearing a
different hat.

## Why two parameters are recovered, not eight

doc 05 §2.1 gives the Level A control vector eight components. This harness infers two of
them, `n_0` and `T_e`, via :func:`~vpl.inverse.map.maximum_a_posteriori` over
:class:`~vpl.inverse.priors.default_control_prior`'s own `n_0` and `T_e` marginals. The
remaining six are held at their RP-1 reference values, for two different reasons:

1. **`T_i`, `phi_RF`, `gamma_se` and `kappa` have exactly zero effect on this configuration's
   prediction.** `T_i` does not enter the Bohm speed because this harness uses L0's default
   `gamma_i = GAMMA_I_COLD_ION = 0` (the registered value that reproduces doc 01 §2.2's
   tabulated numbers — see `vpl.physics.analytic.sheath`'s module docstring); `phi_RF` is
   inert because the run is DC; `gamma_se` is not read anywhere in `AnalyticSheathSolver.
   solve`; `kappa` never reaches the OES chain because :class:`~vpl.instruments.oes.
   instrument.MaxwellianEedf` — used here as its own docstring says to, "the verification
   fallback, not the default" — ignores it. Recovering a parameter the forward chain cannot
   see would not be inference; it would be reporting the prior back at whoever asked. This
   is checked directly, independently of this module, by `test_gamma_e_is_insensitive_to_
   the_fixed_control_parameters`.
2. **`V_w` is not insensitive** — a single-parameter sweep shows the OES prediction changes
   sharply away from the truth's bias — but jointly optimising `(n_0, T_e, V_w)` from a
   realistic starting point (rather than one that happens to coincide with the truth) walks
   into a shallow, correlated ridge and stops well short of the true point while still
   reporting `converged=True`. This is the `n_0`-`T_e` correlation doc 05 §6.2 predicts
   (`Gamma_i ~ n_0 sqrt(T_e)`), compounded by a `V_w` direction that a single emission line
   at coarse spatial resolution does not resolve crisply enough to break the ridge in the
   time this harness can afford to spend per test. doc 05 §2.1 itself frames `V_w` as
   "informative — supply-measured, sigma = 1%", i.e. close to independently known in a real
   apparatus, so fixing it here is a defensible scope decision for a *first* closed loop and
   not a fabricated one — but it is a real limitation, stated rather than hidden, and a
   genuine `(n_0, T_e, V_w)` joint recovery is future work, not something this harness
   quietly claims.

## The OES instrument this harness uses is a verification fixture, not doc 02's instrument

The level system built in :func:`_reference_level_system` is "argon-shaped, not argon" —
three levels and one emission line, following the same convention
`packages/vpl-instruments/tests/oes_system.py` uses for the OES package's own unit tests:
energies and degeneracies chosen to look like the real Ar I metastable/resonant structure of
doc 02 §6.3, with Born-like synthetic cross sections rather than an LXCat set. Every other
component — the spectrograph, the calibration standard's uncertainty, the detection gate,
the Poisson/Gaussian switch — reads its numbers from the real parameter registry via
`Spectrograph.from_registry` and `OesInstrument` exactly as doc 04 §5 specifies them. What
is synthetic here is the atomic data, not the optics or the statistics, and the reason is
doc 00 C2: fitting a real LXCat cross-section set to a CR model that reproduces a printed
line ratio is its own piece of work, already scoped elsewhere, and reusing the package's own
"not argon" verification convention is more honest than inventing a second one.
"""

